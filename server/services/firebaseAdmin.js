import { initializeApp, getApps, cert } from 'firebase-admin/app';
import { getAuth } from 'firebase-admin/auth';
import dotenv from 'dotenv';

dotenv.config();

let isInitialized = false;

export const initializeFirebaseAdmin = () => {
  if (isInitialized && getApps().length > 0) {
    return true;
  }
  try {
    if (getApps().length === 0) {
      if (process.env.FIREBASE_SERVICE_ACCOUNT) {
        let serviceAccount;
        try {
          serviceAccount = JSON.parse(process.env.FIREBASE_SERVICE_ACCOUNT);
        } catch (e) {
          serviceAccount = process.env.FIREBASE_SERVICE_ACCOUNT;
        }
        initializeApp({
          credential: cert(serviceAccount),
        });
        isInitialized = true;
        console.log('[Firebase Admin] Initialized from FIREBASE_SERVICE_ACCOUNT');
      } else if (
        process.env.FIREBASE_PROJECT_ID &&
        process.env.FIREBASE_CLIENT_EMAIL &&
        process.env.FIREBASE_PRIVATE_KEY
      ) {
        const formattedPrivateKey = process.env.FIREBASE_PRIVATE_KEY.replace(/\\n/g, '\n');
        initializeApp({
          credential: cert({
            projectId: process.env.FIREBASE_PROJECT_ID,
            clientEmail: process.env.FIREBASE_CLIENT_EMAIL,
            privateKey: formattedPrivateKey,
          }),
        });
        isInitialized = true;
        console.log('[Firebase Admin] Initialized from FIREBASE_PROJECT_ID & keys');
      }
    } else {
      isInitialized = true;
    }
  } catch (err) {
    console.error('[Firebase Admin] Initialization notice:', err.message);
  }
  return isInitialized;
};

// Immediate initialization attempt
initializeFirebaseAdmin();

/**
 * Verify a Firebase ID Token generated by Firebase Phone Authentication.
 * Decodes and cryptographically validates the token with Google Firebase servers.
 * @param {string} idToken
 * @returns {Promise<string>} The verified E.164 phone number
 */
export const verifyFirebasePhoneIdToken = async (idToken) => {
  initializeFirebaseAdmin();
  if (getApps().length === 0) {
    throw new Error('Firebase Admin SDK is not initialized on the server.');
  }
  const auth = getAuth();
  const decodedToken = await auth.verifyIdToken(idToken);
  if (!decodedToken || !decodedToken.phone_number) {
    throw new Error('Firebase token is valid, but does not contain a verified phone number.');
  }
  return decodedToken.phone_number;
};
